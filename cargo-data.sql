-- =====================================================================
--  货物表 模拟数据 (PostgreSQL)
--
--  执行前提(缺一不可, 因为货物要引用它们):
--    1. initial.sql          —— cargo 表和 set_time_fields() 触发器已存在
--    2. cargo-type-data.sql  —— 货物种类 1-12
--    3. order-data.sql       —— 订单 1783100000000000001 ~ 012
--
--  14 条货物, 覆盖了查询和删除保护需要验证的几种情况:
--    · 按货物名称前缀查: cargo_type_id 落在 1(钢材) / 2(钢管) / 12(钢材) 上的共 7 条,
--                        所以 cargoTypeName=钢 应命中 **7 条**;
--                        id=5 挂的是 3(不锈钢板), 名字里有"钢"但不在开头, 不该被命中
--    · 按订单号查:       订单 ...001 有 2 条, ...003 有 2 条, ...011 有 2 条
--    · 删除保护(能删):    种类 10(散装粮食) / 11(机械设备) **没有任何货物引用**,
--                        删它们会成功 —— 用来验证"没被引用就能删"这条路
--    · 删除保护(删不掉):  种类 1 / 2 / 3 / 4 / ... 都被货物引用,
--                        删任一个都会返回 409; 批量删除时只要混进一个被引用的就整批拒绝
--
--  注意: Cargo 的 cargo_type_id / order_id / quantity 三列在库里是 **not null**
--        (见 initial.sql 的说明), 所以这里每行都必须给全, 不能留空。
--
--  编写约定:
--    1. insert_time / update_time 不写值, 留 null 交给 set_time_fields() 触发器填北京时间。
--    2. id 显式指定 + on conflict do nothing, 保证脚本可以重复执行。
--    3. id 是 generated by default as identity: 显式插入 id 不会推进自增序列,
--       所以末尾必须把序列对齐到 max(id) + 1。
-- =====================================================================

begin;

insert into cargo (id, cargo_type_id, order_id, quantity) values
    (1,  1,    '1783100000000000001', 120),
    (2,  4,    '1783100000000000001', 80),
    (3,  1,    '1783100000000000002', 60),
    (4,  9,    '1783100000000000002', 25),
    (5,  3,    '1783100000000000003', 200),
    (6,  2,    '1783100000000000003', 150),
    (7,  5,    '1783100000000000004', 500),
    (8,  7,    '1783100000000000006', 30),
    (9,  6,    '1783100000000000007', 45),
    (10, 12,   '1783100000000000008', 90),
    (11, 8,    '1783100000000000010', 300),
    (12, 1,    '1783100000000000011', 75),
    (13, 1,    '1783100000000000011', 10),
    (14, 2,    '1783100000000000012', 220)
on conflict do nothing;

-- 显式插入 identity 列不会移动序列, 这里手动同步。
-- setval(..., n, false) 表示下一次 nextval 返回 n, 所以取 max(id) + 1。
select setval(
    pg_get_serial_sequence('cargo', 'id'),
    coalesce((select max(id) from cargo), 0) + 1,
    false
);

commit;
