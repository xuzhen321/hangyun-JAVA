--    3. trailer-data.sql         —— 拖车号 沪A12345 等已存在
--
--  8 条提空箱记录, 覆盖了列表和筛选需要验证的情况:
--    · 按箱号前缀筛:  containerNo=CSNU → 命中 **2 条**(id 1、7, 同一个箱提了两次)
--    · 按拖车号前缀筛: trackNo=沪A     → 命中 **2 条**(id 1、8, 同一辆车跑了两次)
--    · 按进场时间区间: 2026-10-01 ~ 2026-10-08 → 命中 **5 条**(id 4、5、6、7、8)
--    · 出场时间可以留空: id 5、7、8 是**还没出场**的(dc_out_date 为 null),
--                       用来验证前端对空时间的处理
--
--  ⚠️ 所有箱号和拖车号都取自上面两个种子文件, 对得上, 所以"箱号/拖车号必须存在"
--     那道校验能通过。
--
--  编写约定:
--    1. insert_time / update_time 不写值, 留 null 交给 set_time_fields() 触发器。
--       (dc_in_date / dc_out_date 是业务字段, 由本脚本显式给值。)
--    2. id 显式指定 + on conflict do nothing, 保证脚本可以重复执行。
--    3. id 是 generated by default as identity: 显式插入 id 不会推进自增序列,
--       所以末尾必须把序列对齐到 max(id) + 1。
-- =====================================================================

