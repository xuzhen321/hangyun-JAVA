-- 显式插入 identity 列不会移动序列, 这里手动同步。
-- setval(..., n, false) 表示下一次 nextval 返回 n, 所以取 max(id) + 1。
select setval(
    pg_get_serial_sequence('container_trailer_record', 'id'),
    coalesce((select max(id) from container_trailer_record), 0) + 1,
    false
);

commit;
