-- =====================================================================
--  船舶类型字典 初始数据 (PostgreSQL)
--
--  执行前提: 已执行 initial.sql。本表不引用其他表, 只依赖第 1 步。
--
--  ⚠️ 这一版的 GT / NT / DWT 是**带双引号的列名**(建表脚本里就是大写),
--     所以插入时必须加双引号, 否则 PG 会折叠成小写、报"列不存在"。
--
--  ⚠️ 吨位/尺寸都是**该类船的典型值**, 编的, 不是任何一条真实船的数据
--     (真实船舶的具体参数在 vessel 上; 这里只是船型的参考规格)。
--
--  编写约定: insert_time / update_time 留 null 交给触发器; id 显式指定 +
--            on conflict do nothing 保证可重复执行; 末尾同步自增序列。
-- =====================================================================

begin;

insert into ship_type (id, type, "GT", length, width, "NT", "DWT") values
    (1, '集装箱船', 90000.00,  300.00, 40.00, 45000.00,  100000.00),
    (2, '散货船',   40000.00,  190.00, 32.00, 20000.00,   75000.00),
    (3, '油轮',     60000.00,  245.00, 42.00, 30000.00,  110000.00),
    (4, '杂货船',   20000.00,  150.00, 23.00, 10000.00,   25000.00),
    (5, '滚装船',   50000.00,  200.00, 32.00, 25000.00,   20000.00)
on conflict do nothing;

-- 显式插入 identity 列不会移动序列, 这里手动同步。
select setval(
    pg_get_serial_sequence('ship_type', 'id'),
    coalesce((select max(id) from ship_type), 0) + 1,
    false
);

commit;
