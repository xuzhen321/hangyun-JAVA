    (12, '钢材',     '热轧卷板(与 id=1 同名)', 3100.00, 1.60)
on conflict do nothing;

-- 显式插入 identity 列不会移动序列, 这里手动同步。
-- setval(..., n, false) 表示下一次 nextval 返回 n, 所以取 max(id) + 1。
select setval(
    pg_get_serial_sequence('cargo_type', 'id'),
    coalesce((select max(id) from cargo_type), 0) + 1,
    false
);

commit;
