--
--  12 条货物种类, 覆盖了列表和搜索需要验证的几种情况:
--    · 名称前缀匹配: id 1 / 2 / 12 都以"钢"开头, 查 name=钢 应命中 **3 条**;
--                    id 3 是"不锈钢板", 名字里有"钢"但**不在开头**, 不该被命中
--                    (命中了就说明前缀匹配退化成了包含匹配)
--    · 重名:         id 1 和 id 12 都叫"钢材" —— 库里 name **没有唯一约束**,
--                    允许重名。用来验证"同名行各自独立"以及删除拦截提示的表现。
--                    将来若给 name 加了唯一约束, 这条要删掉(否则 on conflict 会静默跳过)。
--    · 可空字段:     id 10 / 11 的重量和体积是 null, 用来验证前端对空值的处理
--    · 小数位数:     decimal(10,2), 数据里有 0.02 这种小值也有 3100.00 这种大值
--
--  编写约定:
--    1. insert_time / update_time 不写值, 留 null 交给 set_time_fields() 触发器填北京时间。
--    2. id 显式指定 + on conflict do nothing, 保证脚本可以重复执行。
--    3. id 是 generated by default as identity: 显式插入 id 不会推进自增序列,
--       所以末尾必须把序列对齐到 max(id) + 1。
-- =====================================================================

