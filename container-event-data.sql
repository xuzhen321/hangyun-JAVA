    (2,  'CSNU1234567', '0', 1, 1, 2, 'N', '2026-09-30 09:15:00'),   -- 装船中
    (3,  'CSNU1234567', '1', 1, 1, 3, 'N', '2026-09-30 18:00:00'),   -- 航行中
