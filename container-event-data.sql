--  10 条物流事件, 覆盖了查询和轨迹需要验证的情况:
--    · **完整轨迹**: 箱号 CSNU1234567 有 5 条事件(id 1-5), 按时间升序构成一条完整的链路:
--        预安排 → 装船中 → 航行中 → 卸货中 → 已完成
--        所以 GET /containers/CSNU1234567/track 应该返回 **5 条**, 且是时间升序的
--    · **逻辑删除**: id=10 的状态是"已删除"(6) —— 它不该出现在轨迹里, 也不该出现在列表里
--        所以不带状态筛选的列表应该是 **9 条**(不是 10 条)
--    · **预计 vs 实际**: id 1、6、9 是"预计"(Y), 其余是"实际"(N)
--    · **来源**: id 3、4、8、9 是"船公司"(1), 其余是"港区"(0)
--
--  ⚠️ 船名(vsl_name)能不能显示, 取决于 step 5 的航次有没有填 vsl_id:
--     voyage-data.sql 现在会给航次 1-4 填上船舶, 所以轨迹里能看到船名。
--     如果航次的 vsl_id 还是 null, 视图左连接后船名就是空的(不影响其它字段)。
--
--  编写约定: insert_time / update_time 留 null 交给触发器; id 显式指定 +
--            on conflict do nothing 保证可重复执行; 末尾同步自增序列。
-- =====================================================================

