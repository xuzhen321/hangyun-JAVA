--  执行前提(缺一不可):
--    1. initial.sql          —— container_event 表和触发器已存在
--    2. event-status-data.sql —— 事件状态 1-6（6 是内置的"已删除"）
--    3. container-data.sql   —— 箱号 CSNU1234567 等已存在
--    4. port-data.sql        —— 发生地港口 1/2/3/9 已存在
--    5. voyage-data.sql      —— 航次 1/2 已存在
